CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS iris_staging;

CREATE TABLE IF NOT EXISTS iris_staging.commercial_poi_staging (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source TEXT NOT NULL DEFAULT 'openstreetmap',
    osm_type TEXT NOT NULL,
    osm_id BIGINT NOT NULL,

    feature_type TEXT NOT NULL,
    name TEXT,
    tags JSONB NOT NULL DEFAULT '{}'::jsonb,

    geom geometry(MultiPolygon, 25832) NOT NULL,
    area_sqm DOUBLE PRECISION NOT NULL
        CHECK (area_sqm > 0),

    estimated_pv_kwp DOUBLE PRECISION,
    association_status TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT commercial_poi_unique_source
        UNIQUE (source, osm_type, osm_id, feature_type),

    CONSTRAINT commercial_poi_feature_type_check
        CHECK (feature_type IN ('building', 'parking')),

    CONSTRAINT commercial_poi_pv_check
        CHECK (estimated_pv_kwp IS NULL OR estimated_pv_kwp >= 0)
);

CREATE INDEX IF NOT EXISTS commercial_poi_geom_idx
    ON iris_staging.commercial_poi_staging
    USING GIST (geom);
